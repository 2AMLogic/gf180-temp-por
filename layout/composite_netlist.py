# ==========================================================================
# SPICE parsing
# ==========================================================================

_UNIT = re.compile(r"^([0-9.eE+-]+)\s*([a-zA-Z]*)$")
_SI = {"": 1.0, "f": 1e-15, "p": 1e-12, "n": 1e-9, "u": 1e-6, "m": 1e-3, "k": 1e3}


def _number(token: str) -> float:
    match = _UNIT.match(token)
    if not match:
        raise CompositeError(f"cannot parse numeric token {token!r}")
    value, suffix = match.groups()
    scale = _SI.get(suffix.lower())
    if scale is None:
        raise CompositeError(f"unsupported unit suffix in {token!r}")
    return float(value) * scale


def _unescape(node: str) -> str:
    """KLayout escapes leading ``$`` in written SPICE node names."""
    return node[1:] if node.startswith("\\") else node


def _cards(text: str) -> list[tuple[str, str]]:
    """``(card, preceding comment)`` with ``+`` continuations joined.

    The writer wraps long lines -- a wide ``.SUBCKT`` pin list, for
    instance -- so a parser that reads physical lines silently loses pins.
    """
    out: list[tuple[str, str]] = []
    comment = ""
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("*"):
            comment = line
            continue
        if line.startswith("+"):
            if not out:
                raise CompositeError("continuation line with nothing to continue")
            out[-1] = (f"{out[-1][0]} {line[1:].strip()}", out[-1][1])
            continue
        out.append((line, comment))
        comment = ""
    return out


class Device:
    """One 4-terminal MOS card, from either side of the compare."""

    __slots__ = ("name", "klass", "nodes", "length", "width", "params", "comment")

    def __init__(self, name, klass, nodes, length, width, params=None, comment=""):
        self.name = name
        self.klass = klass
        self.nodes = list(nodes)  # d g s b
        self.length = length
        self.width = width
        self.params = dict(params or {})
        self.comment = comment

    def key(self, rename=lambda net: net) -> tuple:
        """Order-insensitive identity: source/drain are interchangeable."""
        drain, gate, source, body = (rename(n) for n in self.nodes)
        return (
            self.klass,
            round(self.length, 6),
            round(self.width, 6),
            tuple(sorted((drain, source))),
            gate,
            body,
        )

    def __repr__(self):  # pragma: no cover - debugging aid
        return f"<Device {self.name} {self.klass} {self.nodes}>"


class Netlist:
    """A parsed MOS-plus-parasitics SPICE netlist."""

    def __init__(self, name, ports, devices, parasitics=None, caps=None):
        self.name = name
        self.ports = list(ports)
        self.devices = list(devices)
        self.parasitics = list(parasitics or [])  # (letter, name, n1, n2, value)
        # Real MiM-cap DEVICE cards from an extraction where the cell's caps
        # are drawn (`lvs_reference.CELLS[cell]["caps"]`), as opposed to the
        # interconnect R/C in `parasitics`: (name, node_a, node_b, value_f,
        # klass). `klt` cannot route a capacitor plate onto a net (the same
        # "Known limitation" `lvs_reference.cap_plate_nets` documents), so
        # each plate node is its own isolated net -- never touched by a MOS
        # device -- and is therefore not part of the net-correspondence
        # graph; see `cap_nets`.
        self.caps = list(caps or [])

    @property
    def cap_nets(self) -> set[str]:
        return {node for _name, node_a, node_b, _value, _klass in self.caps for node in (node_a, node_b)}

    @property
    def nets(self) -> list[str]:
        seen: dict[str, None] = {}
        for device in self.devices:
            for node in device.nodes:
                seen.setdefault(node, None)
        for _letter, _name, node_a, node_b, _value in self.parasitics:
            for node in (node_a, node_b):
                if not node.endswith(PARASITIC_SUFFIX):
                    seen.setdefault(node, None)
        for node in self.cap_nets:
            seen.setdefault(node, None)
        for port in self.ports:
            seen.setdefault(port, None)
        return list(seen)

    def terminals(self) -> dict[str, list[tuple[int, str]]]:
        """net -> [(device index, terminal role)]; d/s share the role ``sd``.

        Built from MOS device terminals alone -- not seeded from
        :attr:`nets` -- so an isolated net that no MOS device touches (a
        drawn MiM cap's plate; see :attr:`cap_nets`) is simply absent from
        the graph the net-correspondence solver searches, rather than
        appearing as a spurious zero-terminal node with no counterpart on
        the reference side.
        """
        roles = ("sd", "g", "sd", "b")
        table: dict[str, list[tuple[int, str]]] = {}
        for index, device in enumerate(self.devices):
            for node, role in zip(device.nodes, roles):
                table.setdefault(node, []).append((index, role))
        return table

    def mos_terminal_counts(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        for device in self.devices:
            for node in device.nodes:
                counts[node] = counts.get(node, 0) + 1
        return counts


def parse_extracted(path: Path) -> Netlist:
    """Parse a ``klt extract`` SPICE output (with or without ``--parasitics``)."""
    ports: list[str] = []
    devices: list[Device] = []
    parasitics: list[tuple[str, str, str, str, float]] = []
    caps: list[tuple[str, str, str, float, str]] = []
    name = path.stem
    for line, pending_comment in _cards(path.read_text()):
        upper = line.upper()
        if upper.startswith(".SUBCKT"):
            fields = line.split()
            name = fields[1]
            ports = fields[2:]
            continue
        if upper.startswith(".ENDS"):
            continue
        fields = line.split()
        head = fields[0]
        if head[0] in "Mm":
            nodes = [_unescape(n) for n in fields[1:5]]
            klass = fields[5]
            params = {}
            for field in fields[6:]:
                key, _, value = field.partition("=")
                params[key.upper()] = value
            devices.append(
                Device(
                    name=head[1:],
                    klass=klass,
                    nodes=nodes,
                    length=_number(params["L"]) * 1e6,
                    width=_number(params["W"]) * 1e6,
                    params=params,
                    comment=pending_comment,
                )
            )
        elif head[0] in "Cc" and len(fields) == 5:
            # A real MiM-cap DEVICE card (2 nodes, a value, and the deck's
            # class name), from a cell whose caps are drawn -- see
            # `Netlist.caps`. An interconnect-parasitic C card (below) never
            # carries a class name, so the field count alone distinguishes
            # them without needing the manifest here.
            caps.append(
                (
                    head[1:],
                    _unescape(fields[1]),
                    _unescape(fields[2]),
                    float(fields[3]),
                    fields[4],
                )
            )
        elif head[0] in "RrCc":
            parasitics.append(
                (
                    head[0].upper(),
                    head[1:],
                    _unescape(fields[1]),
                    _unescape(fields[2]),
                    float(fields[3]),
                )
            )
        else:
            raise CompositeError(f"{path}: unexpected card {line!r}")
    return Netlist(name, ports, devices, parasitics, caps)


def parse_reference(path: Path) -> Netlist:
    """Parse a ``layout/lvs_reference.py`` output (plain-element MOS only).

    A cell with drawn (real) MiM caps -- ``lvs_reference.build_cap_cards`` --
    trails its ``.reference.spice`` with ``C<n> ...`` cards after the MOS
    ``M``/``MD`` ones. Those caps are already in the extracted half for a
    drawn cell (``extracted.parasitics``, misfiled as an interconnect
    parasitic but numerically correct -- see :func:`_non_mos_cards`'s
    ``drawn_caps``), so this parser -- MOS devices only, same as ``klt``'s own
    curated deck -- skips them rather than mis-reading a 5-field cap card as
    a 4-terminal MOS one.
    """
    ports: list[str] = []
    devices: list[Device] = []
    name = path.stem
    for line, _comment in _cards(path.read_text()):
        upper = line.upper()
        if upper.startswith(".SUBCKT"):
            fields = line.split()
            name = fields[1]
            ports = fields[2:]
            continue
        if upper.startswith(".ENDS"):
            continue
        fields = line.split()
        if fields[0].upper().startswith("C"):
            continue
        params = {}
        for field in fields[6:]:
            key, _, value = field.partition("=")
            params[key.upper()] = value
        devices.append(
            Device(
                name=fields[0],
                klass=fields[5],
                nodes=fields[1:5],
                length=_number(params["L"]) * 1e6,
                width=_number(params["W"]) * 1e6,
                params=params,
            )
        )
    return Netlist(name, ports, devices)


