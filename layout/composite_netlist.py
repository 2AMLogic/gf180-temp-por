#!/usr/bin/env python3
"""Build the **composite post-layout netlist** for each extracted cell.

    python3 layout/composite_netlist.py                # regenerate layout/composite/
    python3 layout/composite_netlist.py --check        # verify committed outputs are current
    python3 layout/composite_netlist.py --cell bias_core
    python3 layout/composite_netlist.py --extract      # re-run klt extract --parasitics (needs klt)

stdlib only; no PDK, no klayout, no ngspice. ``--extract`` shells out to
``klt`` and is the only mode that needs a toolchain.

What a composite netlist is, and what it is not
-----------------------------------------------
``klt extract`` on every cell under ``layout/cells/`` yields a netlist that is
mostly **MOS-only**: the curated ``gf180mcu`` deck now *declares* ``bjt`` /
``resistor`` / ``cap_mim_*`` device classes, but only ``por_output_chain``
(and ``temp_por_top``, which inherits its geometry) draws the MiM marker
geometry those classes need (klayout-tools#314/#315) -- its two MiM caps
extract as real devices, with isolated plate nodes (see ``Netlist.caps``
below). Every other non-MOS device -- the vertical PNPs, poly resistors, and
``temp_core``'s own MiM cap -- is still not in any extraction
(``layout/README.md`` -> "Known deck limits"). ``klt extract --parasitics``
can only ever hang first-order R/C on the nets that exist in the MOS-only
graph.

So "re-run the suite on the extracted netlist" is not a thing that can be done
literally. What *can* be done, and is what this script builds, is a
**composite**:

* every MOS device, every drawn MiM cap, and every parasitic R/C **from the
  layout** (``layout/reports/<cell>/extracted-parasitics.spice``), and
* every other non-MOS device **verbatim from the golden schematic export**
  (``design/netlist/<cell>.spice``), spliced onto the nets the extraction and
  the schematic are proven to share.

**The passive/bipolar bodies are still ideal.** A result taken on a composite
netlist is evidence about *real interconnect parasitics loading a real MOS
topology* -- the sensing core's high-impedance bias/mirror nodes, the POR
chain's switching nodes, the cross-domain routing -- and nothing else. It is
**not** a parasitic-extracted analog core. Every generated netlist repeats
that in its own header, and every ``sim/`` record taken on one must repeat it
in its **Claim** field (CLAUDE.md: "no claim without a testbench"; the spec is
not relaxed to make a result pass).

How the splice knows where to attach
------------------------------------
The layout labels only a handful of nets, so most extracted nets are anonymous
(``$5``, ``$12``, ...). ``layout/README.md`` used to describe ``por_comparator``'s
sense taps as if ``SNS``/``SNSB`` could be found by name in
``extracted.spice``; they cannot -- **no label is drawn on those tracks**, so
the extractor names them positionally and the schematic names survive only on
the reference side of LVS. Splicing at an *assumed* net name would therefore
silently attach a divider to the wrong node.

This script does not assume. It solves the **net correspondence** between the
extracted netlist and ``layout/cells/<cell>.reference.spice`` (the
schematic-derived LVS reference, generated by ``layout/lvs_reference.py``) --
the same correspondence ``klt lvs`` computes internally but does not report
(filed upstream as tool friction). The solver is a colour-refinement /
backtracking graph isomorphism seeded by the pin names both sides agree on,
and it is **verified**, not trusted: the extracted device multiset translated
through the solved mapping must equal the reference device multiset exactly,
the mapping must be a bijection on nets and pins, and every extracted net that
*does* carry a label must land on a reference net of the same name. Any
failure is an exception, not a warning.

Outputs (all committed as evidence, all regenerated wholesale)
--------------------------------------------------------------
``layout/reports/<cell>/extracted-parasitics.spice`` / ``.json``
    ``klt extract --parasitics`` output. Deliberately a *separate* artifact
    from ``extracted.spice`` / ``extract.json``, which ``run_checks.sh`` keeps
    byte-stable for the DRC/LVS repeatability contract.
``layout/composite/<cell>.composite.spice``
    the composite netlist, in ngspice simulation form, with the golden
    ``.subckt`` port list -- a drop-in replacement for
    ``design/netlist/<cell>.spice``.
``layout/composite/<cell>.audit.json``
    per-net provenance (real-MOS+parasitic vs ideal/schematic), the
    parasitics-coverage counters, and the verdicts on ``layout/README.md``'s
    own "Consequences to carry forward" bullets.
``layout/composite/AUDIT.md``
    the same, rendered.
"""

