AUDIT_HEADER = """\
# Composite post-layout netlists — per-cell audit

**Generated by `layout/composite_netlist.py`. Do not edit.**
Regenerate with `python3 layout/composite_netlist.py`; `--check` fails if this
file is stale.

A *composite* netlist is the layout's own MOS devices and interconnect
parasitics (`klt extract --deck gf180mcu --parasitics`) with the block's
non-MOS devices — vertical PNPs, poly resistors, MiM caps — spliced back in
**verbatim from the golden schematic export**, because none of them is drawn
in any extracted cell (`layout/README.md` → "Known deck limits"). The
convention, and what a result taken on one of these may and may not claim, is
[`layout/README.md` → "Composite post-layout netlists"](../README.md#composite-post-layout-netlists).

**The passives and bipolars below are ideal.** They carry no extracted
geometry, no parasitic R/C and no layout-derived matching. Every `sim/` record
taken against a composite netlist must say so in its **Claim** field.

The tables are generated from the artifacts, not transcribed: each net's row
says whether it came from the layout or only from the schematic, how many MOS
terminals it carries, how many spliced-in (ideal) terminals it carries, and
what parasitic R/C the extractor hung on it.
"""


def render_audit(audits: list[dict]) -> str:
    lines = [AUDIT_HEADER, "## Summary", ""]
    lines.append(
        "| cell | MOS devices (layout) | spliced devices (schematic) | nets | "
        "layout nets | schematic-only nets | nets with parasitics | ΣR (Ω) | ΣC (fF) |"
    )
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
    for audit in audits:
        counts = audit["counts"]
        par = audit["parasitics"]
        lines.append(
            f"| `{audit['cell']}` | {counts['mos_devices_from_layout']} | "
            f"{counts['spliced_devices_from_schematic']} | {counts['nets_total']} | "
            f"{counts['nets_from_layout']} | {counts['nets_schematic_only']} | "
            f"{par['nets_with_parasitics']}/{par['nets_in_extraction']} "
            f"({par['coverage_pct']} %) | {par['total_resistance_ohm']:.0f} | "
            f"{par['total_capacitance_ff']:.1f} |"
        )
    lines += [
        "",
        "The *nets with parasitics* column is the "
        "[klayout-tools#283](https://github.com/2AMLogic/klayout-tools/issues/283)"
        " sanity check: that issue was a silent **zero** on unlabelled nets. A",
        "future regression to zero — or a coverage number that quietly collapses —",
        "is visible here rather than being absorbed as a slightly-optimistic",
        "simulation. `--extract` refuses to write an artifact whose coverage is 0.",
        "",
    ]

    for audit in audits:
        cell = audit["cell"]
        lines += [
            f"## `{cell}` — {audit['note']}",
            "",
            f"Ports: {', '.join(f'`{p}`' for p in audit['ports'])}",
            "",
            "### `layout/README.md`'s own consequences, re-derived",
            "",
            "| verdict | claim | as measured |",
            "| --- | --- | --- |",
        ]
        for claim in audit["readme_claims"]:
            verdict = "holds" if claim["holds"] else "**FAILS**"
            findings = "; ".join(claim["findings"])
            lines.append(f"| {verdict} | {claim['claim']} | {findings} |")
        lines += [
            "",
            "### Nets",
            "",
            "| net | origin | extracted as | MOS terms | ideal terms | R (Ω) | C (fF) |",
            "| --- | --- | --- | --- | --- | --- | --- |",
        ]
        for row in audit["nets"]:
            if row["extracted_nets"]:
                extracted_as = ", ".join(f"`{n}`" for n in row["extracted_nets"])
                if row["labelled_in_layout"]:
                    extracted_as += " (labelled)"
                if row["body_nets_merged"]:
                    extracted_as += (
                        " + body "
                        + ", ".join(f"`{n}`" for n in row["body_nets_merged"])
                    )
            else:
                extracted_as = "—"
            resistance = (
                f"{row['parasitic_r_ohm']:.1f}"
                if row["parasitic_r_ohm"] is not None
                else "—"
            )
            capacitance = (
                f"{row['parasitic_c_ff']:.2f}"
                if row["parasitic_c_ff"] is not None
                else "—"
            )
            origin = (
                "layout (MOS + parasitics)"
                if row["origin"] == "layout"
                else "**schematic only (ideal)**"
            )
            lines.append(
                f"| `{row['net']}`{' *(pin)*' if row['is_pin'] else ''} | {origin} | "
                f"{extracted_as} | {row['mos_terminals']} | "
                f"{row['spliced_terminals']} | {resistance} | {capacitance} |"
            )
        lines += [
            "",
            "### Spliced-in (ideal) devices",
            "",
            "| device | model | nodes | from |",
            "| --- | --- | --- | --- |",
        ]
        for device in audit["spliced_devices"]:
            nodes = ", ".join(f"`{n}`" for n in device["nodes"])
            lines.append(
                f"| `{device['name']}` | `{device['model']}` | {nodes} | "
                f"{device['origin']} |"
            )
        lines.append("")
    return "\n".join(lines)


def generate(cells: list[str]) -> tuple[dict[Path, str], list[dict]]:
    outputs: dict[Path, str] = {}
    audits: list[dict] = []
    for cell in cells:
        text, audit = build_cell(cell)
        outputs[COMPOSITE_DIR / f"{cell}.composite.spice"] = text
        outputs[COMPOSITE_DIR / f"{cell}.audit.json"] = (
            json.dumps(audit, indent=2) + "\n"
        )
        audits.append(audit)
    return outputs, audits


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--cell", help="operate on one cell only")
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate in memory and fail if a committed output differs",
    )
    parser.add_argument(
        "--extract",
        action="store_true",
        help="re-run 'klt extract --parasitics' first (needs klt on PATH)",
    )
    args = parser.parse_args(argv)

    cells = [args.cell] if args.cell else list(CELLS)
    unknown = [cell for cell in cells if cell not in CELLS]
    if unknown:
        print(f"unknown cell(s): {', '.join(unknown)}", file=sys.stderr)
        return 2

    try:
        if args.extract:
            for cell in cells:
                print(f"==> {cell}")
                run_extraction(cell)
        outputs, audits = generate(cells)
        if not args.cell:
            outputs[COMPOSITE_DIR / "AUDIT.md"] = render_audit(audits)
    except CompositeError as error:
        print(f"composite_netlist: {error}", file=sys.stderr)
        return 1

    failures = []
    for path, text in sorted(outputs.items()):
        rel = path.relative_to(REPO_ROOT)
        if args.check:
            if not path.is_file():
                failures.append(f"{rel}: not committed (run without --check)")
            elif path.read_text() != text:
                failures.append(f"{rel}: stale")
            else:
                print(f"ok {rel}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {rel}")

    for line in failures:
        print(f"FAIL {line}", file=sys.stderr)

    broken = [
        (audit["cell"], claim)
        for audit in audits
        for claim in audit["readme_claims"]
        if not claim["holds"]
    ]
    for cell, claim in broken:
        print(
            f"FAIL {cell}: layout/README.md claim does not hold -- "
            f"{claim['claim']} ({'; '.join(claim['findings'])})",
            file=sys.stderr,
        )

    return 1 if failures or broken else 0


if __name__ == "__main__":
    sys.exit(main())
