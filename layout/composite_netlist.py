# Building one cell's composite netlist
# ==========================================================================


def _format_engineering(value: float, unit: str) -> str:
    return f"{value:.6g}{unit}"


def build_cell(cell: str) -> tuple[str, dict]:
    """Return ``(composite netlist text, audit dict)`` for one cell."""
    spec = ref.CELLS[cell]
    check_every_golden_device_is_accounted_for(cell)
    extracted = parse_extracted(REPORTS_DIR / cell / "extracted-parasitics.spice")
    reference = parse_reference(CELLS_DIR / f"{cell}.reference.spice")

    pins = pin_correspondence(extracted, reference)
    mapping = solve_correspondence(extracted, reference, pins)
    verify_correspondence(extracted, reference, mapping)

    aliases = body_aliases(cell)
    cap_pairs = cap_plate_pairs(cell)

    # --- every drawn cap wired, exactly the "every golden device accounted
    # for" guarantee `check_every_golden_device_is_accounted_for` gives the
    # MOS half, extended to caps: a value the manifest never declared, or the
    # wrong DEVICE COUNT, must fail loudly rather than leave a cap floating
    # or silently under/over-count it.
    expected_caps = drawn_cap_unit_count(cell)
    if len(extracted.caps) != expected_caps:
        raise CompositeError(
            f"{cell}: extraction carries {len(extracted.caps)} drawn MiM cap(s), "
            f"the manifest declares {expected_caps}"
        )
    for name, _node_a, _node_b, value, _klass in extracted.caps:
        if round(value, 21) not in cap_pairs:
            raise CompositeError(
                f"{cell}: drawn cap {name!r} extracts at {value:.6g} F, which "
                "matches no golden cap's value -- cannot wire its plates"
            )

    def to_composite(net_extracted: str) -> str:
        net_reference = mapping[net_extracted]
        return composite_name(aliases.get(net_reference, net_reference))

    # --- the net namespace -------------------------------------------------
    # Two distinct extracted nets landing on one composite name would be a
    # short introduced by this script, which is the exact failure the issue
    # asks to rule out by NAME rather than by "it simulated". Exactly one
    # merge is legitimate and is listed device-by-device: the deck's synthetic
    # body nets (the substrate global, each anonymous Nwell) rejoining the
    # schematic node they are tied to.
    layout_nets: dict[str, list[str]] = {}
    for net_extracted in extracted.nets:
        if net_extracted in extracted.cap_nets:
            continue  # a drawn cap's plate net; wired by value, see cap_pairs
        name = to_composite(net_extracted)
        layout_nets.setdefault(name, []).append(net_extracted)
    for name, members in layout_nets.items():
        if len(members) == 1:
            continue
        offenders = [net for net in members if mapping[net] not in aliases]
        if len(offenders) > 1:
            raise CompositeError(
                f"{cell}: extracted nets {offenders!r} both map to composite "
                f"net {name!r} -- the splice would short them"
            )

    ports = ref.subckt_ports(
        (NETLIST_DIR / spec["source"]).read_text(), spec["subckt"]
    )

    # --- the spliced (ideal, schematic) devices ----------------------------
    spliced: list[tuple[str, list[str], str, str]] = []  # name, nodes, trailing, origin
    if "assembly" in spec:
        for inst, sub_cell, rename in ref.instance_renames(cell):
            sub_spec = ref.CELLS[sub_cell]
            drawn_caps = frozenset(sub_spec.get("caps", []))
            for name, nodes, trailing in _non_mos_cards(
                spec["source"], sub_spec["subckt"], drawn_caps
            ):
                spliced.append(
                    (
                        f"X{name[1:]}_{inst}",
                        [composite_name(rename(node)) for node in nodes],
                        trailing,
                        f"{inst} ({sub_cell})",
                    )
                )
    else:
        drawn_caps = frozenset(spec.get("caps", []))
        for name, nodes, trailing in _non_mos_cards(
            spec["source"], spec["subckt"], drawn_caps
        ):
            spliced.append((name, [composite_name(node) for node in nodes], trailing, cell))

    spliced_nets: dict[str, int] = {}
    for _name, nodes, _trailing, _origin in spliced:
        for node in nodes:
            spliced_nets[node] = spliced_nets.get(node, 0) + 1

    new_nets = sorted(net for net in spliced_nets if net not in layout_nets)
    for port in ports:
        if port not in layout_nets and port not in spliced_nets:
            raise CompositeError(
                f"{cell}: golden port {port!r} exists in neither the extraction "
                "nor the spliced devices"
            )

    # --- the parasitics coverage counters (klayout-tools#283 sanity check) --
    parasitic_r = {
        node_a: value
        for letter, _n, node_a, node_b, value in extracted.parasitics
        if letter == "R" and node_b == node_a + PARASITIC_SUFFIX
    }
    parasitic_c = {
        node_b[: -len(PARASITIC_SUFFIX)]: value
        for letter, _n, node_b, _n2, value in (
            (letter, n, a, b, v) for letter, n, a, b, v in extracted.parasitics
        )
        if letter == "C" and node_b.endswith(PARASITIC_SUFFIX)
    }

    mos_counts = extracted.mos_terminal_counts()

    # --- emit --------------------------------------------------------------
    text = _emit(
        cell=cell,
        spec=spec,
        ports=ports,
        extracted=extracted,
        to_composite=to_composite,
        spliced=spliced,
        new_nets=new_nets,
        cap_pairs=cap_pairs,
    )

    audit = _audit(
        cell=cell,
        extracted=extracted,
        reference=reference,
        mapping=mapping,
        pins=pins,
        aliases=aliases,
        layout_nets=layout_nets,
        spliced=spliced,
        spliced_nets=spliced_nets,
        new_nets=new_nets,
        parasitic_r=parasitic_r,
        parasitic_c=parasitic_c,
        mos_counts=mos_counts,
        ports=ports,
        cap_pairs=cap_pairs,
    )
    return text, audit


def _emit(cell, spec, ports, extracted, to_composite, spliced, new_nets, cap_pairs) -> str:
    lines = [
        f"* {cell} -- COMPOSITE post-layout netlist",
        "* generated by layout/composite_netlist.py -- do not edit.",
        "*",
        "* WHAT THIS IS",
        "*   MOS devices and interconnect parasitics taken from the LAYOUT",
        f"*     layout/reports/{cell}/extracted-parasitics.spice",
        "*     (klt extract --deck gf180mcu --parasitics), plus every non-MOS",
        "*     device taken VERBATIM from the golden schematic export",
        f"*     design/netlist/{spec['source']}.",
        "*",
        "* WHAT THIS IS NOT",
        "*   It is NOT a parasitic-extracted analog core. The vertical PNPs,",
        "*   poly resistors and MiM caps below are IDEAL SCHEMATIC DEVICES:",
        "*   they are not drawn in the layout at all, so they carry no",
        "*   extracted geometry, no parasitic R/C, and no layout-derived",
        "*   matching. Any claim recorded against this netlist must say so in",
        "*   the record's Claim field -- what it substantiates is real",
        "*   interconnect parasitics loading the real MOS topology, and",
        "*   nothing more. See layout/composite/AUDIT.md.",
        "*",
        "*   Device bodies are the other place this netlist takes connectivity",
        "*   from the schematic: the curated deck draws no tap or well-label",
        "*   layer, so an extracted body lands on a global substrate net or an",
        "*   anonymous well net. Those are restored to the schematic's own",
        "*   body nodes here, because a floating body cannot be simulated.",
        "*",
        f".subckt {cell} {' '.join(ports)}",
    ]

    lines.append("")
    lines.append("* ---- MOS devices: extracted from the layout ----")
    for device in extracted.devices:
        if device.comment:
            lines.append(device.comment)
        nodes = " ".join(to_composite(node) for node in device.nodes)
        model = f"{device.klass}_03v3"
        params = [
            f"L={_number(device.params['L']) * 1e6:.6g}u",
            f"W={_number(device.params['W']) * 1e6:.6g}u",
            "nf=1",
        ]
        for key, unit in (("AD", "p"), ("AS", "p"), ("PD", "u"), ("PS", "u")):
            if key in device.params:
                scale = 1e12 if unit == "p" else 1e6
                params.append(
                    f"{key.lower()}="
                    f"{_format_engineering(_number(device.params[key]) * scale, unit)}"
                )
        params.append("m=1")
        lines.append(
            f"XM_{_instance_name(device.name)} {nodes} {model} {' '.join(params)}"
        )

    if extracted.caps:
        lines.append("")
        lines.append("* ---- MiM cap devices: extracted from the layout ----")
        lines.append(
            "* Real drawn devices (klayout-tools#314/#315), not spliced from the"
        )
        lines.append(
            "* schematic. `klt` cannot route a capacitor plate onto a net (same"
        )
        lines.append(
            "* limitation `layout/lvs_reference.py` documents for the LVS"
        )
        lines.append(
            "* reference), so the extraction's own plate nodes are isolated --"
        )
        lines.append(
            "* leaving them that way would carry no capacitive loading on the"
        )
        lines.append(
            "* real net at all, so the two plates are wired to the schematic's"
        )
        lines.append(
            "* own nets instead, by value (composite_netlist.cap_plate_pairs;"
        )
        lines.append(
            "* a capacitor is non-polarized, so which plate is which is not"
        )
        lines.append(
            "* observable and does not matter electrically). Bare value, no"
        )
        lines.append(
            "* trailing model name: unlike the LVS reference (a device-CLASS"
        )
        lines.append(
            "* comparison klt's own SPICE reader needs), this is a netlist"
        )
        lines.append(
            "* ngspice simulates, and a trailing token after the value is a"
        )
        lines.append("* parameter ngspice expects to parse, not a class tag.")
        for name, _node_a, _node_b, value, klass in extracted.caps:
            # cap_plate_pairs already resolves to composite-space net names
            # (it runs the schematic's own node names through the same
            # rename()/composite_name() the MOS half uses) -- not through
            # `to_composite`, which maps an EXTRACTED net through the solved
            # correspondence and these plate nodes were never in it.
            net_a, net_b = cap_pairs[round(value, 21)]
            lines.append(f"* {klass}, m=1")
            lines.append(f"C_{_instance_name(name)} {net_a} {net_b} {value:.6g}")

    if extracted.parasitics:
        lines.append("")
        lines.append(
            "* ---- interconnect parasitics: extracted from the layout ----"
        )
        lines.append(
            "* One series R + one lumped C to substrate per net, from the deck's"
        )
        lines.append(
            "* curated sheet-resistance / capacitance table (klt extract"
        )
        lines.append("* --parasitics). First order, not a field solve.")
        for letter, name, node_a, node_b, value in extracted.parasitics:

            def render(node: str) -> str:
                if node.endswith(PARASITIC_SUFFIX):
                    base = node[: -len(PARASITIC_SUFFIX)]
                    return to_composite(base) + PARASITIC_SUFFIX
                return to_composite(node)

            lines.append(
                f"{letter}par_{_instance_name(name)} {render(node_a)} "
                f"{render(node_b)} {value:.6g}"
            )

    lines.append("")
    lines.append("* ---- non-MOS devices: IDEAL, verbatim from the schematic ----")
    if new_nets:
        lines.append(
            "* Nodes introduced by these devices alone (they exist in no"
        )
        lines.append(
            f"* extraction, so they carry no parasitics): {', '.join(new_nets)}"
        )
    for name, nodes, trailing, origin in spliced:
        lines.append(f"* from {origin}")
        lines.append(f"{name} {' '.join(nodes)} {trailing}")

    lines.append("")
    lines.append(f".ends {cell}")
    return "\n".join(lines) + "\n"


def _audit(
    cell,
    extracted,
    reference,
    mapping,
    pins,
    aliases,
    layout_nets,
    spliced,
    spliced_nets,
    new_nets,
    parasitic_r,
    parasitic_c,
    mos_counts,
    ports,
    cap_pairs,
) -> dict:
    nets: list[dict] = []
    for name, members in layout_nets.items():
        # ``members`` is every extracted net that lands on this composite
        # node: normally one, and more only where a synthetic body net
        # rejoined the schematic node it is tied to.
        resistances = [parasitic_r[net] for net in members if net in parasitic_r]
        capacitances = [parasitic_c[net] for net in members if net in parasitic_c]
        nets.append(
            {
                "net": name,
                "extracted_net": members[0] if len(members) == 1 else None,
                "extracted_nets": sorted(members),
                "reference_nets": sorted(mapping[net] for net in members),
                "body_nets_merged": sorted(
                    mapping[net] for net in members if mapping[net] in aliases
                ),
                "labelled_in_layout": any(not net.startswith("$") for net in members),
                "origin": "layout",
                "mos_terminals": sum(mos_counts.get(net, 0) for net in members),
                "spliced_terminals": spliced_nets.get(name, 0),
                "parasitic_r_ohm": round(sum(resistances), 4) if resistances else None,
                "parasitic_c_ff": round(sum(capacitances) * 1e15, 4)
                if capacitances
                else None,
                "is_pin": any(net in pins for net in members),
            }
        )
    for name in new_nets:
        nets.append(
            {
                "net": name,
                "extracted_net": None,
                "extracted_nets": [],
                "reference_nets": [],
                "body_nets_merged": [],
                "labelled_in_layout": False,
                "origin": "schematic",
                "mos_terminals": 0,
                "spliced_terminals": spliced_nets.get(name, 0),
                "parasitic_r_ohm": None,
                "parasitic_c_ff": None,
                "is_pin": False,
            }
        )
    nets.sort(key=lambda row: row["net"])

    # The klayout-tools#283 sanity check, on the extracted netlist's OWN net
    # namespace (not the composite one), cross-checked against what the
    # recorded klt extract JSON says about the same run: a silent zero, or a
    # quiet collapse in coverage, has to be visible rather than absorbed.
    report = json.loads(
        (REPORTS_DIR / cell / "extracted-parasitics.json").read_text()
    )
    reported = report.get("parasitics") or {}
    reported_nets = len(reported.get("nets", []))
    covered = {net for net in parasitic_c}
    if reported_nets != len(covered):
        raise CompositeError(
            f"{cell}: extracted-parasitics.json reports {reported_nets} nets with "
            f"parasitics, the netlist carries {len(covered)}"
        )
    if report.get("net_count") != len(extracted.nets):
        raise CompositeError(
            f"{cell}: extracted-parasitics.json reports {report.get('net_count')} "
            f"nets, the netlist carries {len(extracted.nets)}"
        )
    if reported_nets == 0:
        raise CompositeError(
            f"{cell}: 0 nets carry parasitics -- silent-zero regression "
            "(klayout-tools#283)"
        )

    audit = {
        "cell": cell,
        "note": CELLS[cell]["note"],
        "ports": list(ports),
        "counts": {
            "mos_devices_from_layout": len(extracted.devices),
            "mim_caps_from_layout": len(extracted.caps),
            "spliced_devices_from_schematic": len(spliced),
            "nets_total": len(nets),
            "nets_from_layout": len(layout_nets),
            "nets_schematic_only": len(new_nets),
            "reference_devices": len(reference.devices),
            "extracted_nets": len(extracted.nets),
        },
        "parasitics": {
            "nets_with_parasitics": reported_nets,
            "nets_in_extraction": len(extracted.nets),
            "coverage_pct": round(100.0 * reported_nets / len(extracted.nets), 2),
            "r_cards": sum(1 for p in extracted.parasitics if p[0] == "R"),
            "c_cards": sum(1 for p in extracted.parasitics if p[0] == "C"),
            "total_resistance_ohm": round(sum(parasitic_r.values()), 4),
            "total_capacitance_ff": round(sum(parasitic_c.values()) * 1e15, 4),
            "extracted_nets_without_parasitics": sorted(
                f"{net} -> {composite_name(aliases.get(mapping[net], mapping[net]))}"
                for net in extracted.nets
                if net not in parasitic_c and net not in extracted.cap_nets
            ),
        },
        "mim_caps_from_layout": [
            {
                "name": f"C_{_instance_name(name)}",
                "nodes": list(cap_pairs[round(value, 21)]),
                "value_f": value,
                "model": klass,
            }
            for name, _node_a, _node_b, value, klass in extracted.caps
        ],
        "spliced_devices": [
            {"name": name, "nodes": nodes, "model": trailing.split()[0], "origin": origin}
            for name, nodes, trailing, origin in spliced
        ],
        "schematic_only_nets": new_nets,
        "nets": nets,
        "readme_claims": _check_readme_claims(cell, nets),
    }
    return audit


def _check_readme_claims(cell: str, nets: list[dict]) -> list[dict]:
    """Re-derive layout/README.md's 'Consequences to carry forward' bullets."""
    by_name = {row["net"]: row for row in nets}
    results = []
    for claim in CELLS[cell]["readme"]:
        findings = []
        holds = True
        for net in claim["nets"]:
            row = by_name.get(net)
            if row is None:
                findings.append(f"{net}: absent from the composite netlist entirely")
                holds = False
                continue
            in_extraction = row["origin"] == "layout"
            if in_extraction != claim["extracted"]:
                findings.append(
                    f"{net}: {'in' if in_extraction else 'not in'} the extraction, "
                    f"claim says {'in' if claim['extracted'] else 'not in'}"
                )
                holds = False
                continue
            if "mos_terminals" in claim and row["mos_terminals"] != claim["mos_terminals"]:
                findings.append(
                    f"{net}: {row['mos_terminals']} MOS terminal(s), "
                    f"claim says {claim['mos_terminals']}"
                )
                holds = False
                continue
            if "labelled" in claim and row["labelled_in_layout"] != claim["labelled"]:
                findings.append(
                    f"{net}: labelled={row['labelled_in_layout']}, "
                    f"claim says labelled={claim['labelled']}"
                )
                holds = False
                continue
            detail = (
                f"{net}: extracted as {row['extracted_net']}"
                if in_extraction
                else f"{net}: schematic-only"
            )
            if in_extraction:
                detail += f", {row['mos_terminals']} MOS terminal(s)"
                detail += (
                    ", labelled" if row["labelled_in_layout"] else ", unlabelled"
                )
            findings.append(detail)
        results.append({"claim": claim["claim"], "holds": holds, "findings": findings})
    return results


