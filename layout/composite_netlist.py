def _golden_devices(cell_source: str, subckt: str) -> dict[str, dict]:
    text = (NETLIST_DIR / cell_source).read_text()
    body = ref.subckt_body(text, subckt)
    return ref.parse_devices(body)


def check_every_golden_device_is_accounted_for(cell: str) -> None:
    """No golden device may fall between the two halves of the composite.

    A MOS device the layout manifest does not list would be dropped from the
    extracted half (it is not drawn) *and* skipped by the spliced half (it is
    a MOS card), so it would vanish silently. ``lvs_reference.build_cards``
    checks the other direction -- a manifest device missing from the golden
    netlist -- so between them every device in the schematic is either drawn
    or deliberately spliced.
    """

    def check(spec: dict) -> None:
        devices = _golden_devices(spec["source"], spec["subckt"])
        listed = set(spec["devices"])
        missing = sorted(set(devices) - listed)
        if missing:
            raise CompositeError(
                f"{cell}: golden MOS device(s) {', '.join(missing)} are in "
                f"design/netlist/{spec['source']} but not in "
                "lvs_reference.CELLS -- they would be in neither half of the "
                "composite netlist"
            )

    spec = ref.CELLS[cell]
    if "assembly" in spec:
        for _inst, sub_cell, _rename in ref.instance_renames(cell):
            check(ref.CELLS[sub_cell])
    else:
        check(spec)


def _non_mos_cards(
    cell_source: str, subckt: str, drawn_caps: frozenset[str] = frozenset()
) -> list[tuple[str, list[str], str]]:
    """(name, nodes, trailing text) for every non-MOS card in a golden subckt.

    ``drawn_caps`` is a manifest's own ``caps`` list (``lvs_reference.CELLS``):
    the golden MiM cards that a *drawn* cell now instantiates for real
    (klayout-tools#314/#315; ``lvs_reference.build_cap_cards``). Those are
    already in the extracted half via ``extracted-parasitics.spice`` -- they
    are excluded here, not spliced, or the composite netlist would carry the
    same capacitor twice: once real, once ideal.
    """
    text = (NETLIST_DIR / cell_source).read_text()
    cards: list[tuple[str, list[str], str]] = []
    for line in ref.subckt_body(text, subckt):
        fields = line.split()
        if not fields[0].upper().startswith("X"):
            continue
        if fields[0] in drawn_caps:
            continue
        # The MOS cards are the ones lvs_reference knows how to convert; every
        # other X card is a device this deck cannot extract.
        if any(field in ref.DEVICE_CLASS for field in fields[1:]):
            continue
        model_index = None
        for index, field in enumerate(fields[1:], start=1):
            if "=" not in field:
                model_index = index
        if model_index is None:
            raise CompositeError(f"cannot find the model name in {line!r}")
        nodes = fields[1:model_index]
        trailing = " ".join(fields[model_index:])
        cards.append((fields[0], nodes, trailing))
    return cards


def body_aliases(cell: str) -> dict[str, str]:
    """Reference body-net name -> the schematic net it stands for.

    ``lvs_reference.py`` rewrites every NMOS body onto the deck's global
    substrate net and every PMOS body onto a per-drawn-well net, because that
    is all the deck can see. A simulation netlist cannot leave them there --
    an anonymous well net is a floating body. This restores the schematic's
    own body nodes, and is the one place the composite netlist takes
    connectivity from the schematic for a device the layout *does* draw. It is
    called out in the generated header for exactly that reason.
    """
    aliases: dict[str, str] = {}

    def record(body_ref: str, body_schematic: str) -> None:
        previous = aliases.setdefault(body_ref, body_schematic)
        if previous != body_schematic:
            raise CompositeError(
                f"{cell}: body net {body_ref!r} stands for both {previous!r} "
                f"and {body_schematic!r} in the schematic"
            )

    def walk(spec: dict, rename=lambda net: net) -> None:
        devices = _golden_devices(spec["source"], spec["subckt"])
        well_of = {
            member: well
            for well, members in spec.get("wells", {}).items()
            for member in members
        }
        for name in spec["devices"]:
            device = devices[name]
            _letter, klass = ref.DEVICE_CLASS[device["model"]]
            body_ref = ref.SUBSTRATE_NET if klass == "nfet" else well_of[name]
            record(rename(body_ref), rename(device["nodes"][3]))
        # A drawn edge dummy is not in the schematic, so it contributes no
        # body alias of its own -- it sits in a well some real device already
        # resolved. A dummy in a well nothing else occupies would leave that
        # body floating in simulation, so that is an error, not a default.
        for dummy in spec.get("dummies", []):
            if dummy["class"] == "nfet":
                continue
            if rename(dummy["well"]) not in aliases:
                raise CompositeError(
                    f"{cell}: drawn dummy sits in well {dummy['well']!r}, which "
                    "no schematic device occupies -- nothing says what to tie "
                    "its body to"
                )

    spec = ref.CELLS[cell]
    if "assembly" in spec:
        for _inst, sub_cell, rename in ref.instance_renames(cell):
            walk(ref.CELLS[sub_cell], rename)
    else:
        walk(spec)
    return aliases


def cap_plate_pairs(cell: str) -> dict[float, tuple[str, str]]:
    """Drawn-cap value -> the (real net, real net) its two plates stand for.

    Same situation as :func:`body_aliases`, for the other place ``klt``
    cannot see a connection it is physically there: a capacitor's plates
    extract as their own isolated, self-connected nodes (``klt``'s
    ``CapacitorDevice`` "Known limitation"; also why
    ``lvs_reference.cap_plate_nets`` names the LVS reference's plate nodes
    ``XCDG.NDG`` rather than ``NDG``). A composite netlist cannot leave a
    drawn cap floating -- it would carry no capacitive loading on the real
    net at all, defeating the entire point of drawing it -- so this restores
    the schematic's own two nets for each drawn cap, keyed by value.

    Keyed by value rather than by instance because that is all the
    extraction can tell two identical parallel units apart by: their plate
    nodes are isolated, so nothing in ``extracted-parasitics.spice``
    distinguishes ``XCTIM``'s unit 1 from unit 3 either (the reference's own
    ``.N`` unit numbering is arbitrary for the same reason). A capacitor is
    non-polarized, so within one value class every unit tying the same net
    pair is electrically interchangeable; two golden caps sharing a value
    but wiring different net pairs is refused rather than guessed at.
    """

    def golden_pairs(spec: dict, rename=lambda net: net) -> dict[float, tuple[str, str]]:
        names = spec.get("caps", [])
        if not names:
            return {}
        source = NETLIST_DIR / spec["source"]
        caps = ref.parse_capacitors(ref.subckt_body(source.read_text(), spec["subckt"]))
        pairs: dict[float, tuple[str, str]] = {}
        for name in names:
            cap = caps[name]
            width_um = ref.to_um(cap["params"]["c_width"])
            length_um = ref.to_um(cap["params"]["c_length"])
            value = width_um * length_um * ref.MIM_AREA_CAP_F_UM2
            key = round(value, 21)
            node_a, node_b = (composite_name(rename(node)) for node in cap["nodes"])
            previous = pairs.get(key)
            if previous is not None and previous not in ((node_a, node_b), (node_b, node_a)):
                raise CompositeError(
                    f"{cell}: drawn caps {value:.6g} F apart wire different net "
                    f"pairs ({previous} vs {(node_a, node_b)}) -- cannot auto-wire "
                    "extracted plates by value alone"
                )
            pairs[key] = (node_a, node_b)
        return pairs

    spec = ref.CELLS[cell]
    if "assembly" in spec:
        pairs: dict[float, tuple[str, str]] = {}
        for _inst, sub_cell, rename in ref.instance_renames(cell):
            for key, value_pair in golden_pairs(ref.CELLS[sub_cell], rename).items():
                previous = pairs.get(key)
                if previous is not None and previous not in (
                    value_pair,
                    value_pair[::-1],
                ):
                    raise CompositeError(
                        f"{cell}: drawn caps {key:.6g} F apart wire different net "
                        f"pairs ({previous} vs {value_pair}) across sub-cells -- "
                        "cannot auto-wire extracted plates by value alone"
                    )
                pairs[key] = value_pair
        return pairs
    return golden_pairs(spec)


def drawn_cap_unit_count(cell: str) -> int:
    """How many drawn-cap DEVICES (post ``m=`` multiplier) a cell's manifest
    declares -- what :func:`build_cell` requires ``extracted.caps`` to equal
    exactly, the same "every golden device accounted for" guarantee
    :func:`check_every_golden_device_is_accounted_for` gives the MOS half.
    """

    def count(spec: dict) -> int:
        names = spec.get("caps", [])
        if not names:
            return 0
        source = NETLIST_DIR / spec["source"]
        caps = ref.parse_capacitors(ref.subckt_body(source.read_text(), spec["subckt"]))
        return sum(ref.cap_units(caps[name]) for name in names)

    spec = ref.CELLS[cell]
    if "assembly" in spec:
        return sum(
            count(ref.CELLS[sub_cell])
            for _inst, sub_cell, _rename in ref.instance_renames(cell)
        )
    return count(spec)


def composite_name(net: str) -> str:
    return net.replace(".", INSTANCE_SEPARATOR)


def _instance_name(stem: str) -> str:
    """A SPICE-safe instance name.

    The extractor names a device or a parasitic after the net it belongs to,
    and those names carry characters ngspice treats as syntax: ``$`` for an
    anonymous net, ``|`` where two labels were drawn on one net
    (``EN|RESETn``). Left alone, ngspice mis-parses the card into a
    different-arity element and fails with a confusing "unknown parameter".
    """
    return "".join(
        character if character.isalnum() or character == "_" else "_"
        for character in stem
    )


