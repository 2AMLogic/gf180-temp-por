def _refine(netlist: Netlist, seed: dict[str, str], rounds: int, shared: dict) -> dict:
    """One colour-refinement pass set; returns net -> integer colour.

    ``shared`` is the colour dictionary both netlists intern into, so a colour
    means the same thing on both sides -- that is what makes the two
    partitions comparable at all.
    """

    def intern(token) -> int:
        return shared.setdefault(token, len(shared))

    terminals = netlist.terminals()
    colour = {net: intern(("seed", seed.get(net, ""))) for net in terminals}
    for _ in range(rounds):
        device_colour = []
        for device in netlist.devices:
            drain, gate, source, body = device.nodes
            device_colour.append(
                intern(
                    (
                        "dev",
                        device.klass,
                        round(device.length, 6),
                        round(device.width, 6),
                        tuple(sorted((colour[drain], colour[source]))),
                        colour[gate],
                        colour[body],
                    )
                )
            )
        updated = {}
        for net, terms in terminals.items():
            updated[net] = intern(
                (
                    "net",
                    colour[net],
                    tuple(sorted((device_colour[i], role) for i, role in terms)),
                )
            )
        if len(set(updated.values())) == len(set(colour.values())):
            colour = updated
            break
        colour = updated
    return colour


def _classes(colour: dict[str, int]) -> dict[int, list[str]]:
    out: dict[int, list[str]] = {}
    for net, value in colour.items():
        out.setdefault(value, []).append(net)
    for nets in out.values():
        nets.sort()
    return out


def solve_correspondence(
    extracted: Netlist, reference: Netlist, pin_pairs: dict[str, str]
) -> dict[str, str]:
    """Solve extracted-net -> reference-net, seeded by the agreed pin names.

    Colour refinement first; anything it leaves ambiguous is resolved by
    backtracking (guess one pair, re-refine, recurse). The result is verified
    by the caller against the device multiset -- a wrong guess cannot survive
    that, so the search cannot silently return a plausible-but-wrong answer.
    """
    rounds = max(len(extracted.nets), len(reference.nets)) + 2

    def attempt(forced: dict[str, str], depth: int) -> dict[str, str] | None:
        if depth > len(extracted.nets) + 2:  # pragma: no cover - safety net
            return None
        shared: dict = {}
        seed_extracted = {net: f"#{i}" for i, net in enumerate(sorted(forced))}
        seed_reference = {
            forced[net]: f"#{i}" for i, net in enumerate(sorted(forced))
        }
        colour_e = _refine(extracted, seed_extracted, rounds, shared)
        colour_r = _refine(reference, seed_reference, rounds, shared)
        classes_e = _classes(colour_e)
        classes_r = _classes(colour_r)
        if set(classes_e) != set(classes_r):
            return None
        mapping: dict[str, str] = {}
        ambiguous: list[int] = []
        for value, nets_e in classes_e.items():
            nets_r = classes_r[value]
            if len(nets_e) != len(nets_r):
                return None
            if len(nets_e) == 1:
                mapping[nets_e[0]] = nets_r[0]
            else:
                ambiguous.append(value)
        if not ambiguous:
            return mapping
        # Guess inside the smallest ambiguous class and re-refine.
        value = min(ambiguous, key=lambda v: (len(classes_e[v]), v))
        net_e = classes_e[value][0]
        for net_r in classes_r[value]:
            deeper = dict(forced)
            deeper[net_e] = net_r
            result = attempt(deeper, depth + 1)
            if result is not None:
                return result
        return None

    mapping = attempt(dict(pin_pairs), 0)
    if mapping is None:
        raise CompositeError(
            "could not solve the extracted<->reference net correspondence; "
            "the two netlists are not isomorphic under the pin seeding "
            "(re-run layout/run_checks.sh -- LVS should be failing too)"
        )
    return mapping


def pin_correspondence(extracted: Netlist, reference: Netlist) -> dict[str, str]:
    """Match extracted pins to reference ports by name.

    Extraction joins two labels drawn on one net with ``|`` (``EN|RESETn``),
    so an extracted pin is matched on any of its aliases. Requires a perfect
    matching -- a pin set that does not line up means the committed LVS run
    and this script are looking at different things.
    """
    available = set(reference.ports)
    pairs: dict[str, str] = {}
    for pin in extracted.ports:
        aliases = [alias for alias in pin.split("|") if alias in available]
        if len(aliases) != 1:
            raise CompositeError(
                f"extracted pin {pin!r} matches {len(aliases)} reference port(s) "
                f"{aliases}; reference ports are {sorted(reference.ports)}"
            )
        pairs[pin] = aliases[0]
        available.discard(aliases[0])
    if available:
        raise CompositeError(
            f"reference port(s) {sorted(available)} have no extracted pin"
        )
    return pairs


def verify_correspondence(
    extracted: Netlist, reference: Netlist, mapping: dict[str, str]
) -> None:
    """Prove the mapping, rather than trusting the solver that produced it.

    A drawn MiM cap's isolated plate nets (:attr:`Netlist.cap_nets`) are
    real extracted nets but touch no MOS device, so they never enter the
    net-correspondence graph (:meth:`Netlist.terminals`) and are excluded
    from the count here too -- they are emitted directly from their own
    extracted node names (see ``build_cell``), not through this mapping.
    """
    solved_nets = set(extracted.nets) - extracted.cap_nets
    if set(mapping) != solved_nets:
        raise CompositeError(
            f"mapping covers {len(mapping)} of {len(solved_nets)} extracted "
            "nets needing correspondence"
        )
    if len(set(mapping.values())) != len(mapping):
        raise CompositeError("mapping is not injective -- two nets would be shorted")
    if set(mapping.values()) != set(reference.nets) | set(reference.ports):
        missing = (set(reference.nets) | set(reference.ports)) - set(mapping.values())
        extra = set(mapping.values()) - (set(reference.nets) | set(reference.ports))
        raise CompositeError(
            f"mapping is not onto the reference nets (missing {sorted(missing)}, "
            f"unexpected {sorted(extra)})"
        )

    left = sorted(device.key(lambda net: mapping[net]) for device in extracted.devices)
    right = sorted(device.key() for device in reference.devices)
    if left != right:
        raise CompositeError(
            "the extracted device list, translated through the solved net "
            "mapping, is not the reference device list -- the correspondence "
            "is wrong (or LVS is no longer a match)"
        )

    # A net the layout actually labels must land on the reference net of the
    # same name. This is an independent check on the topological solve: it
    # uses information (the drawn label) the solver was never given for
    # anything but the pins.
    for net_e, net_r in mapping.items():
        if net_e.startswith("$"):
            continue
        for alias in net_e.split("|"):
            tail = net_r.rsplit(".", 1)[-1]
            if alias == tail:
                break
        else:
            raise CompositeError(
                f"extracted net {net_e!r} carries a drawn label but the solved "
                f"correspondence puts it on reference net {net_r!r}"
            )


