def run_extraction(cell: str) -> None:
    """Re-run ``klt extract --parasitics`` and record it as a new artifact.

    Deliberately writes ``extracted-parasitics.spice`` / ``.json`` rather than
    touching ``extracted.spice`` / ``extract.json``: ``run_checks.sh`` keeps
    those byte-stable as the DRC/LVS flow's own repeatability contract.
    """
    request = json.loads((CELLS_DIR / f"{cell}.lvs.json").read_text())
    out_dir = REPORTS_DIR / cell
    out_dir.mkdir(parents=True, exist_ok=True)
    command = [
        "klt",
        "extract",
        str((CELLS_DIR / f"{cell}.gds").relative_to(REPO_ROOT)),
        "--deck",
        DECK,
        "--top",
        cell,
        "--parasitics",
        "-o",
        str((out_dir / "extracted-parasitics.spice").relative_to(REPO_ROOT)),
        "--format",
        "json",
    ]
    if request["layout"].get("top_cell_pins", False):
        command.append("--top-cell-pins")
    print(f"    $ {' '.join(command)}")
    result = subprocess.run(
        command, cwd=REPO_ROOT, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        raise CompositeError(
            f"{cell}: klt extract --parasitics exited {result.returncode}\n"
            f"{result.stdout}\n{result.stderr}"
        )
    report = json.loads(result.stdout)
    (out_dir / "extracted-parasitics.json").write_text(
        json.dumps(report, indent=2) + "\n"
    )
    parasitics = report.get("parasitics") or {}
    net_count = report.get("net_count", 0)
    covered = len(parasitics.get("nets", []))
    if covered == 0:
        # klayout-tools#283: parasitics silently reading zero on unlabelled
        # nets is a regression this repo hit before and must never eat again.
        raise CompositeError(
            f"{cell}: --parasitics produced 0 nets with parasitics out of "
            f"{net_count} -- silent-zero regression (klayout-tools#283)"
        )
    print(f"    parasitics on {covered}/{net_count} nets")


